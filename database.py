"""Acesso ao PostgreSQL do NuvemPay."""
import os
import psycopg
from psycopg.rows import dict_row


def conectar():
    url = os.environ.get('DATABASE_URL')
    if not url:
        raise RuntimeError('Configure DATABASE_URL para PostgreSQL.')
    return psycopg.connect(url, row_factory=dict_row, connect_timeout=10)


def criar_banco():
    with conectar() as banco:
        banco.execute('''CREATE TABLE IF NOT EXISTS usuarios (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            senha TEXT NOT NULL,
            saldo_centavos BIGINT NOT NULL DEFAULT 0 CHECK (saldo_centavos >= 0)
        )''')
        banco.execute('''CREATE TABLE IF NOT EXISTS transacoes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            remetente_id BIGINT NOT NULL REFERENCES usuarios(id),
            destinatario_id BIGINT NOT NULL REFERENCES usuarios(id),
            valor_centavos BIGINT NOT NULL CHECK (valor_centavos > 0),
            data TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CHECK (remetente_id <> destinatario_id)
        )''')
        banco.execute('CREATE INDEX IF NOT EXISTS idx_transacoes_remetente ON transacoes (remetente_id, id DESC)')
        banco.execute('CREATE INDEX IF NOT EXISTS idx_transacoes_destinatario ON transacoes (destinatario_id, id DESC)')

if __name__ == '__main__':
    criar_banco()
